// TRD §4.2 step 4: graph delta — structural change only. Node identity is the
// node id; content edits inside an unchanged id are NOT part of the delta.

import type { GraphDelta, GraphSnapshot } from '@atlas/contracts';

export function diffGraphs(prev: GraphSnapshot, next: GraphSnapshot): GraphDelta {
  const previousNodeIds = new Set(prev.nodes.map((node) => node.id));
  const nextNodeIds = new Set(next.nodes.map((node) => node.id));
  const previousEdgeIds = new Set(prev.edges.map((edge) => edge.id));
  const nextEdgeIds = new Set(next.edges.map((edge) => edge.id));

  return {
    addedNodes: next.nodes.filter((node) => !previousNodeIds.has(node.id)),
    removedNodeIds: prev.nodes.filter((node) => !nextNodeIds.has(node.id)).map((node) => node.id),
    addedEdges: next.edges.filter((edge) => !previousEdgeIds.has(edge.id)),
    removedEdgeIds: prev.edges.filter((edge) => !nextEdgeIds.has(edge.id)).map((edge) => edge.id),
  };
}

/**
 * Concise English one-liner, e.g. '+2 files, −1 file, +3 dependencies, −1 dependency'.
 * Removed entries carry only ids, so counts key off this package's own id
 * scheme: nodes `file:…`, edges `edge:import:…` (generated by buildGraph).
 */
export function deltaSummary(delta: GraphDelta): string {
  const addedFiles = delta.addedNodes.filter((node) => node.type === 'file').length;
  const removedFiles = delta.removedNodeIds.filter((id) => id.startsWith('file:')).length;
  const addedDeps = delta.addedEdges.filter((edge) => edge.kind === 'import').length;
  const removedDeps = delta.removedEdgeIds.filter((id) => id.startsWith('edge:import:')).length;

  const parts: string[] = [];
  if (addedFiles > 0) parts.push(`+${addedFiles} ${plural(addedFiles, 'file', 'files')}`);
  if (removedFiles > 0) parts.push(`−${removedFiles} ${plural(removedFiles, 'file', 'files')}`);
  if (addedDeps > 0) parts.push(`+${addedDeps} ${plural(addedDeps, 'dependency', 'dependencies')}`);
  if (removedDeps > 0) parts.push(`−${removedDeps} ${plural(removedDeps, 'dependency', 'dependencies')}`);

  return parts.length > 0 ? parts.join(', ') : 'No structural changes';
}

function plural(count: number, singular: string, pluralForm: string): string {
  return count === 1 ? singular : pluralForm;
}
