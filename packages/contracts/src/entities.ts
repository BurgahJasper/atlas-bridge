// ── Locale / level primitives (TRD §5, §12: extensible locale system) ───────

export type Locale = 'en' | 'es';
export const LOCALES: Locale[] = ['en', 'es'];

export type LearningLevel = 'beginner' | 'intermediate' | 'advanced';

export const LEVELS: LearningLevel[] = ['beginner', 'intermediate', 'advanced'];

// ── Provenance (TRD §2.3, §5.3: every fact is traceable) ────────────────────
export interface EvidenceRef {
  sha: string;
  path?: string;
  startLine?: number;
  endLine?: number;
  url?: string;
}

export type Basis = 'explicit' | 'inferred';
export type Confidence = 'low' | 'medium' | 'high';

export interface Claim {
  text: string;
  basis: Basis;
  confidence: Confidence;
  evidenceRefs: EvidenceRef[];
}

/** Pedagogy text is separated from repository-specific claims (TRD §5.3). */
export interface TimelineStory {
  snapshotSha: string;
  milestones: MilestoneStoryPart[];
  locale: Locale;
  summary: string;
  claims: Claim[];
  untranslatedTerms: string[];
  /** True when generated by the offline mock/cached fallback (TRD §10.1.7). */
  offline: boolean;
}

export interface MilestoneStoryPart {
  milestoneId: string;
  sha: string;
  title: string;
  narrative: string;
  claims: Claim[];
}

export interface NodeExplanation {
  nodeId: string;
  /** What this file/module appears to be responsible for. */
  purpose: string;
  detail: string;
  claims: Claim[];
  locale: Locale;
  offline: boolean;
}

// ── Repository facts (TRD §6 data model) ────────────────────────────────────

export type Provider = 'github';

export interface Repository {
  id: string;
  provider: Provider;
  owner: string;
  name: string;
  visibility: 'public' | 'private';
  defaultBranch: string;
  licenseSpdx: string | null;
  description: string | null;
  stars: number;
  lastIndexedAt: string | null;
}

export type SnapshotStatus =
  | 'pending'
  | 'analyzing'
  | 'ready'
  | 'partial'
  | 'failed'
  | 'stale'
  | 'rate-limited'
  | 'unsupported';

export interface SnapshotScope {
  commitLimit: number;
  maxMilestoneFiles: number;
  maxFileBytes: number;
}

export interface Snapshot {
  id: string;
  repositoryId: string;
  /** Milestone commit SHA this snapshot describes. */
  sha: string;
  /** First commit SHA that was fetched into the analysis window. */
  rootSha: string;
  time: string;
  sourceScope: SnapshotScope;
  manifestKey: string;
  status: SnapshotStatus;
  /** Analysis warnings that describe this snapshot (persisted, shown in overview). */
  notes?: string[];
}

export interface GraphNode {
  id: string;
  snapshotId: string;
  /** Repo-relative path; folders have a trailing "/". */
  path: string;
  label: string;
  type: 'file' | 'folder' | 'module';
  language?: string;
  size?: number;
}

export type EdgeKind = 'import' | 'folder' | 'association';

export interface GraphEdge {
  id: string;
  snapshotId: string;
  source: string;
  target: string;
  kind: EdgeKind;
  evidenceRef?: EvidenceRef;
  /** True when we cannot prove the relationship (TRD §4.1 fact-graph rule). */
  inferred?: boolean;
}

export interface GraphSnapshot {
  snapshotId: string;
  sha: string;
  nodes: GraphNode[];
  edges: GraphEdge[];
}

export interface GraphDelta {
  addedNodes: GraphNode[];
  removedNodeIds: string[];
  addedEdges: GraphEdge[];
  removedEdgeIds: string[];
}

export type MilestoneChangeKind = 'release' | 'merge' | 'structural' | 'other';

export interface Milestone {
  id: string;
  repositoryId: string;
  snapshotId: string;
  sha: string;
  title: string;
  rank: number;
  changeKind: MilestoneChangeKind;
  changeSummary: string;
  /** ISO date of the commit. */
  time: string;
  evidenceRefs: EvidenceRef[];
}

// ── AI / explanations (TRD §5) ──────────────────────────────────────────────

export type ExplanationTask = 'history' | 'node' | 'translation' | 'mission' | 'hint';

export interface Explanation {
  id: string;
  snapshotId: string;
  subjectId: string;
  task: ExplanationTask;
  locale: Locale;
  level: LearningLevel;
  modelId: string;
  schemaVersion: 1;
  createdAt: string;
  citations: EvidenceRef[];
  confidence: Confidence;
  /** Discriminated content payload (TimelineStory | NodeExplanation | ...). */
  content: TimelineStory | NodeExplanation | HintResponse | Mission;
}

export interface GlossaryTerm {
  term: string;
  translations: { [L in Locale]?: string };
  kind: 'library' | 'concept' | 'schema';
}

// ── Learning / missions (TRD §6, FR-06, FR-07) ──────────────────────────────

export type MissionStepKind = 'read' | 'comprehension' | 'quiz' | 'edit';

/**
 * Deterministic validators only — scoring never relies solely on model
 * self-evaluation (TRD §5.2). v0 fixtures use text/pattern checks; v1 adds
 * sandboxed checks when ANALYSIS_MODE=worker (TRD §7 code execution rule).
 */
export type ValidationSpec =
  | { type: 'text-match'; mustInclude: string[]; caseSensitive?: boolean; minLength?: number }
  | { type: 'pattern'; file: string; regex: string; flags?: string }
  | { type: 'diff-touches'; path: string; mustNotInclude?: string[] }
  | { type: 'quiz'; oneOf: string[] };

export interface MissionStep {
  id: string;
  kind: MissionStepKind;
  /** Steps are authored locale-neutral; `hint` and UI copy are localized via dictionaries. */
  instructions: { [L in Locale]: string };
  targetPaths: string[];
  excerptSharas?: string[];
  /** Quiz choices shown to the learner (validation.oneOf holds the correct answers). */
  options?: string[];
  validation: ValidationSpec;
}

export interface Mission {
  id: string;
  repoId: string;
  scopeSha: string;
  title: string;
  steps: MissionStep[];
  rubric: string[];
  maintainerApproved: boolean;
  issueUrl?: string;
  estimatedMinutes: number;
}

export interface HintResponse {
  stepId: string;
  hintLevel: 1 | 2 | 3;
  text: string;
  locale: Locale;
}

export interface LearningPath {
  id: string;
  repoId: string;
  scopeSha: string;
  targetAudience: LearningLevel;
  /** Step ids in recommended order. */
  localeNeutralSteps: string[];
  version: 1;
}

export interface StepResult {
  stepId: string;
  passed: boolean;
  at: string;
}

export interface LearnerProgress {
  id: string;
  userOrAnonymousId: string;
  missionId: string;
  locale: Locale;
  completedSteps: string[];
  results: StepResult[];
  updatedAt: string;
}

